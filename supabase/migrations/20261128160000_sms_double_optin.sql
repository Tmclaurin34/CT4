-- Package "sms" / 01: SMS double opt-in for public check-ins.
-- Additive and idempotent: one new table, two functions, no change to any existing
-- row, column or function. No backfill: existing sms_consent=true rows stay valid, and
-- owner-entered customers are untouched.
--
-- A check-in that ticks the marketing box now creates a PENDING request here (with its
-- evidence) instead of setting customers.sms_consent. The customer is asked once by
-- text ("Reply YES ..."); an inbound YES within 7 days, from the number that is still on
-- the customer's record, flips sms_consent=true and the request records the confirmation.
-- Pending is never consent: nothing that sends texts reads this table.

create table if not exists public.sms_consent_requests (
  id                   bigint generated by default as identity primary key,
  user_id              uuid        not null,             -- the business
  customer_id          bigint      not null references public.customers (id) on delete cascade,
  phone                text        not null,             -- +1XXXXXXXXXX, as texted
  kind                 text        not null default 'marketing',
  source               text        not null default 'checkin',
  status               text        not null default 'pending',  -- pending | confirmed | superseded
  requested_at         timestamptz not null default now(),
  evidence             jsonb       not null default '{}'::jsonb, -- ip, user_agent, form_version, at, decision
  confirm_attempted_at timestamptz,                      -- set when a confirmation text was claimed
  confirm_status       text,                             -- sent | failed | unconfirmed (timeout)
  confirm_sid          text,                             -- Twilio SID of the "Reply YES" text
  confirm_sent_at      timestamptz,
  confirm_error        text,
  confirmed_at         timestamptz,
  yes_sid              text,                             -- Twilio SID of the customer's YES
  yes_at               timestamptz,
  yes_body             text
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'sms_consent_requests_phone_chk') then
    alter table public.sms_consent_requests
      add constraint sms_consent_requests_phone_chk check (phone ~ '^\+1[2-9][0-9]{2}[2-9][0-9]{6}$');
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sms_consent_requests_status_chk') then
    alter table public.sms_consent_requests
      add constraint sms_consent_requests_status_chk check (status in ('pending', 'confirmed', 'superseded'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sms_consent_requests_kind_chk') then
    alter table public.sms_consent_requests
      add constraint sms_consent_requests_kind_chk check (kind in ('marketing'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sms_consent_requests_confirm_status_chk') then
    alter table public.sms_consent_requests
      add constraint sms_consent_requests_confirm_status_chk
      check (confirm_status is null or confirm_status in ('sent', 'failed', 'unconfirmed'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'sms_consent_requests_evidence_size_chk') then
    alter table public.sms_consent_requests
      add constraint sms_consent_requests_evidence_size_chk check (pg_column_size(evidence) <= 8192);
  end if;
end $$;

create index if not exists sms_consent_requests_lookup_idx
  on public.sms_consent_requests (user_id, phone, requested_at desc);
create index if not exists sms_consent_requests_customer_idx
  on public.sms_consent_requests (customer_id);

-- Evidence includes IP addresses: server-only. RLS on with no policies, and no API-role grants.
alter table public.sms_consent_requests enable row level security;
revoke all on table public.sms_consent_requests from public, anon, authenticated;
grant select, insert, update on table public.sms_consent_requests to service_role;

-- ── clicktide_sms_optin_request ──────────────────────────────────────────────
-- Records a check-in's marketing opt-in request and decides, atomically per business +
-- phone, whether ONE confirmation text may go out now: at most one per phone per
-- business per 24 hours, never to a customer who texted STOP, never when the caller
-- has no sender (p_can_send=false). Returns {ok, request_id, send, reason}.
create or replace function public.clicktide_sms_optin_request(
  p_user uuid, p_customer bigint, p_phone text, p_evidence jsonb, p_can_send boolean
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_c      record;
  v_recent boolean;
  v_send   boolean := false;
  v_reason text;
  v_id     bigint;
  v_ev     jsonb := coalesce(p_evidence, '{}'::jsonb);
begin
  if p_user is null or p_customer is null or p_phone is null
     or p_phone !~ '^\+1[2-9][0-9]{2}[2-9][0-9]{6}$' then
    return jsonb_build_object('ok', false, 'send', false, 'reason', 'invalid');
  end if;
  if jsonb_typeof(v_ev) <> 'object' or pg_column_size(v_ev) > 4096 then
    v_ev := jsonb_build_object('evidence_dropped', 'not an object or too large');
  end if;
  perform pg_advisory_xact_lock(hashtextextended('sms_optin:' || p_user::text || ':' || p_phone, 0));

  select c.id, c.sms_consent, c.sms_unsubscribed_at, c.phone
    into v_c
    from public.customers c
   where c.id = p_customer and c.user_id = p_user
   for update;
  if not found then
    return jsonb_build_object('ok', false, 'send', false, 'reason', 'no_customer');
  end if;
  if right(regexp_replace(coalesce(v_c.phone, ''), '\D', '', 'g'), 10) <> right(p_phone, 10) then
    return jsonb_build_object('ok', false, 'send', false, 'reason', 'phone_mismatch');
  end if;
  if coalesce(v_c.sms_consent, false) then
    return jsonb_build_object('ok', true, 'send', false, 'reason', 'already_consented');
  end if;

  select exists (
    select 1 from public.sms_consent_requests r
     where r.user_id = p_user and r.phone = p_phone
       and r.confirm_attempted_at > now() - interval '24 hours'
  ) into v_recent;

  if v_c.sms_unsubscribed_at is not null then
    v_reason := 'opted_out';
  elsif not coalesce(p_can_send, false) then
    v_reason := 'no_sender';
  elsif v_recent then
    v_reason := 'recently_asked';
  else
    v_send := true;
    v_reason := 'send';
  end if;

  insert into public.sms_consent_requests (user_id, customer_id, phone, evidence, confirm_attempted_at)
  values (p_user, p_customer, p_phone, v_ev || jsonb_build_object('decision', v_reason),
          case when v_send then now() end)
  returning id into v_id;

  return jsonb_build_object('ok', true, 'request_id', v_id, 'send', v_send, 'reason', v_reason);
end;
$$;

-- ── clicktide_sms_optin_confirm ──────────────────────────────────────────────
-- An inbound YES / Y / START from p_phone to this business's number. Flips
-- customers.sms_consent=true ONLY when this business has a pending request for this
-- phone that is at most 7 days old and was actually asked (a confirmation text was
-- attempted and not known to have failed), the customer has not texted STOP, AND the
-- customer's phone on file is STILL the number that was asked and that replied. If the
-- phone was edited after the ask (owner edit, POS sync), consent would land on a number
-- that never agreed: the stale request is marked superseded and nothing is consented
-- (reason 'phone_changed'); the customer has to check in again with the new number.
-- Records the YES (SID, time, body) on the request. Otherwise changes nothing.
create or replace function public.clicktide_sms_optin_confirm(
  p_user uuid, p_phone text, p_yes_sid text, p_yes_body text
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_r     record;
  v_c     record;
  v_stale int;
begin
  if p_user is null or p_phone is null or p_phone !~ '^\+1[2-9][0-9]{2}[2-9][0-9]{6}$' then
    return jsonb_build_object('confirmed', false, 'reason', 'invalid');
  end if;
  perform pg_advisory_xact_lock(hashtextextended('sms_optin:' || p_user::text || ':' || p_phone, 0));

  -- The newest eligible request whose customer STILL has this phone. FOR UPDATE locks the
  -- request and the customer row; under READ COMMITTED a concurrent phone edit is
  -- re-checked against the join condition before the row is returned.
  select r.id, r.customer_id, r.requested_at, r.confirm_sid into v_r
    from public.sms_consent_requests r
    join public.customers c on c.id = r.customer_id and c.user_id = p_user
   where r.user_id = p_user and r.phone = p_phone and r.kind = 'marketing'
     and r.status = 'pending'
     and r.confirm_attempted_at is not null
     and coalesce(r.confirm_status, '') <> 'failed'
     and r.requested_at >= now() - interval '7 days'
     and right(regexp_replace(coalesce(c.phone, ''), '\D', '', 'g'), 10) = right(p_phone, 10)
   order by r.requested_at desc, r.id desc
   limit 1
   for update;
  if not found then
    -- An otherwise-eligible request exists but its customer's phone changed since the ask:
    -- retire it, so a YES from this number can never consent the customer's new number.
    with stale as (
      update public.sms_consent_requests r
         set status = 'superseded',
             evidence = r.evidence || jsonb_build_object('superseded_reason', 'phone_changed',
                                                         'superseded_at', now())
        from public.customers c
       where c.id = r.customer_id
         and r.user_id = p_user and r.phone = p_phone and r.kind = 'marketing'
         and r.status = 'pending'
         and r.confirm_attempted_at is not null
         and coalesce(r.confirm_status, '') <> 'failed'
         and r.requested_at >= now() - interval '7 days'
         and (c.user_id is distinct from p_user
              or right(regexp_replace(coalesce(c.phone, ''), '\D', '', 'g'), 10) <> right(p_phone, 10))
      returning r.id
    )
    select count(*) into v_stale from stale;
    if v_stale > 0 then
      return jsonb_build_object('confirmed', false, 'reason', 'phone_changed');
    end if;
    return jsonb_build_object('confirmed', false, 'reason', 'no_pending');
  end if;

  select c.id, c.sms_consent, c.sms_unsubscribed_at, c.phone into v_c
    from public.customers c
   where c.id = v_r.customer_id and c.user_id = p_user
   for update;
  if not found then
    return jsonb_build_object('confirmed', false, 'reason', 'no_customer');
  end if;
  -- Belt and braces: the customer row is locked, so this is the phone consent attaches to.
  if right(regexp_replace(coalesce(v_c.phone, ''), '\D', '', 'g'), 10) <> right(p_phone, 10) then
    return jsonb_build_object('confirmed', false, 'reason', 'phone_changed');
  end if;
  if v_c.sms_unsubscribed_at is not null then
    return jsonb_build_object('confirmed', false, 'reason', 'opted_out');
  end if;

  update public.customers
     set sms_consent = true, sms_consent_at = now()
   where id = v_c.id and sms_consent is not true;

  update public.sms_consent_requests
     set status = 'confirmed', confirmed_at = now(), yes_at = now(),
         yes_sid = left(p_yes_sid, 64), yes_body = left(p_yes_body, 160)
   where id = v_r.id;

  update public.sms_consent_requests
     set status = 'superseded'
   where user_id = p_user and phone = p_phone and status = 'pending' and id <> v_r.id;

  return jsonb_build_object('confirmed', true, 'request_id', v_r.id, 'customer_id', v_c.id,
                            'requested_at', v_r.requested_at, 'confirm_sid', v_r.confirm_sid);
end;
$$;

revoke all on function public.clicktide_sms_optin_request(uuid, bigint, text, jsonb, boolean) from public, anon, authenticated;
revoke all on function public.clicktide_sms_optin_confirm(uuid, text, text, text) from public, anon, authenticated;
grant execute on function public.clicktide_sms_optin_request(uuid, bigint, text, jsonb, boolean) to service_role;
grant execute on function public.clicktide_sms_optin_confirm(uuid, text, text, text) to service_role;
